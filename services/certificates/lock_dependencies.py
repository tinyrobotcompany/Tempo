"""Generate a hash lock for the actual production target: CPython 3.14, Linux amd64.

Only wheels are allowed. Tests on other operating systems use requirements-test.in.
Run with a maintained pip version; inspect and audit the resulting lock before commit.
"""
import hashlib
from pathlib import Path
import subprocess
import sys
import tempfile
import zipfile
from email.parser import BytesParser

root = Path(__file__).resolve().parent
with tempfile.TemporaryDirectory() as temporary:
    subprocess.run([sys.executable, "-m", "pip", "download", "--only-binary=:all:",
                    "--platform", "manylinux_2_28_x86_64", "--platform", "manylinux2014_x86_64",
                    "--python-version", "3.14", "--implementation", "cp", "--abi", "cp314", "--abi", "abi3",
                    "-r", str(root / "requirements.in"), "-d", temporary], check=True)
    lines = []
    for wheel in Path(temporary).glob("*.whl"):
        with zipfile.ZipFile(wheel) as archive:
            name = next(n for n in archive.namelist() if n.endswith(".dist-info/METADATA"))
            metadata = BytesParser().parsebytes(archive.read(name))
        digest = hashlib.sha256(wheel.read_bytes()).hexdigest()
        lines.append(f"{metadata['Name']}=={metadata['Version']} --hash=sha256:{digest}")
    (root / "requirements.txt").write_text(
        "# Linux amd64 / CPython 3.14 wheel lock. Generated by lock_dependencies.py.\n" +
        "\n".join(sorted(lines, key=str.lower)) + "\n")
