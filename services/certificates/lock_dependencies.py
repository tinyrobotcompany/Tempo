"""Generate a hash lock for the actual production target: CPython 3.14, Linux amd64.

Only wheels are allowed. --test locks Linux amd64 and macOS arm64 test wheels.
Run with a maintained pip version; inspect and audit the resulting lock before commit.
"""
import argparse
import hashlib
from pathlib import Path
import subprocess
import sys
import tempfile
import zipfile
from email.parser import BytesParser

root = Path(__file__).resolve().parent
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument("--test", action="store_true")
args = parser.parse_args()
with tempfile.TemporaryDirectory() as temporary:
    folder = Path(temporary)
    source = root / "requirements.in"
    targets = [["manylinux_2_28_x86_64", "manylinux2014_x86_64"]]
    if args.test:
        # Preserve reviewed versions; resolving upgrades is a separate operation.
        source = folder / "pins.txt"
        source.write_text("\n".join(line.split()[0] for line in (root / "requirements-test.txt").read_text().splitlines()
                                    if line and not line.startswith(("#", " "))))
        targets += [["macosx_14_0_arm64"]]
    locks = {}
    for index, platforms in enumerate(targets):
        destination = folder / str(index)
        command = [sys.executable, "-m", "pip", "download", "--only-binary=:all:"]
        for platform in platforms:
            command += ["--platform", platform]
        subprocess.run(command + ["--python-version", "3.14", "--implementation", "cp", "--abi", "cp314", "--abi", "abi3",
                                   "-r", str(source), "-d", str(destination)], check=True)
        for wheel in destination.glob("*.whl"):
            with zipfile.ZipFile(wheel) as archive:
                name = next(n for n in archive.namelist() if n.endswith(".dist-info/METADATA"))
                metadata = BytesParser().parsebytes(archive.read(name))
            requirement = f"{metadata['Name']}=={metadata['Version']}"
            locks.setdefault(requirement, set()).add(hashlib.sha256(wheel.read_bytes()).hexdigest())
    filename = "requirements-test.txt" if args.test else "requirements.txt"
    platforms = "Linux amd64 and macOS arm64" if args.test else "Linux amd64"
    (root / filename).write_text(
        f"# {platforms} / CPython 3.14 wheel lock. Generated by lock_dependencies.py.\n" +
        "\n".join(requirement + " " + " ".join("--hash=sha256:" + digest for digest in sorted(locks[requirement]))
                   for requirement in sorted(locks, key=str.lower)) + "\n")
